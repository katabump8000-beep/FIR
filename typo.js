// ============================================================

function getCorrectedCommand(text) {
    if (!text) return null;

    let cleaned = String(text).trim();
    if (cleaned.startsWith(".")) cleaned = cleaned.slice(1).trim();
    if (!cleaned) return null;

    const normalizedFull = normalizeText(cleaned);
    if (TYPO_MAP[normalizedFull]) {
        const cmd = TYPO_MAP[normalizedFull];
        if (ALLOWED_COMMANDS.has(cmd)) return "." + cmd;
    }

    for (const [key, cmd] of Object.entries(TYPO_MAP)) {
        if (!ALLOWED_COMMANDS.has(cmd)) continue;

        if (normalizedFull === key) {
            return "." + cmd;
        }

        if (normalizedFull.startsWith(key + " ")) {
            const rest = cleaned.slice(key.length).trim();
            return "." + cmd + (rest ? " " + rest : "");
        }

        if (normalizedFull.endsWith(" " + key)) {
            const idx = cleaned.lastIndexOf(" ");
            const prefix = cleaned.slice(0, idx).trim();
            return "." + cmd + (prefix ? " " + prefix : "");
        }
    }

    return null;
}

// ============================================================
// المعالجة الرئيسية
// ============================================================

async function handleTypo(sock, jid, msg, text, db, cleanSender, isBotOwner) {
    try {
        if (!text) return false;
        if (String(text).startsWith(".")) return false;
        if (text.length > 60) return false;

        if (text.includes("؟") || text.includes("?") || text.includes("!")) {
            if (text.length > 30) return false;
        }

        if (text.split("\n").length > 1) return false;

        const corrected = getCorrectedCommand(text);
        if (!corrected) return false;

        try {
            const { handleCommand } = require("./commands");

            const fakeMsg = {
                ...msg,
                message: { conversation: corrected }
            };

            const handled = await handleCommand(sock, jid, fakeMsg, {
                db,
                sender: msg?.key?.participantPn ||
                        msg?.key?.participant_pn ||
                        msg?.key?.participant ||
                        msg?.key?.remoteJid,
                cleanSender,
                isGroup: true,
                isBotOwner: Boolean(isBotOwner),
                botNumber: cleanSender,
                text: corrected
            });

            return handled !== false;

        } catch (err) {
            console.error("❌ typo exec error:", err?.message);
            return false;
        }

    } catch (error) {
        console.error("❌ خطأ في handleTypo:", error?.message || error);
        return false;
    }
}

